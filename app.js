function flip() { S.ses.side = 'back'; card(); }
function go(n) { const s = S.ses, j = s.i + n; if (j >= 0 && j < s.list.length) { s.i = j; s.side = 'front'; card(); } }
function rate(r) {
  const c = S.ses.list[S.ses.i], old = P.cards[c.id] || {};
  P.cards[c.id] = { r, t: Date.now(), n: (old.n || 0) + 1 };
  S.ses.got[c.id] = r; save(P); pushOne(c.id); advance();
}
function advance() { const s = S.ses; if (s.i < s.list.length - 1) { s.i++; s.side = 'front'; card(); } else summary(); }

