async function getData(lang) {
  if (!S.data[lang]) {
    const r = await fetch(`data/v1_${lang}.json`);
    if (!r.ok) throw new Error(r.status);
    S.data[lang] = await r.json();
  }
  return S.data[lang];
}

function stats(list) {
  const rs = list.map(c => rating(c.id));
  return { rated: rs.filter(Boolean).length, sure: rs.filter(r => r >= 3).length, rev: rs.filter(r => r && r <= 2).length };
}

