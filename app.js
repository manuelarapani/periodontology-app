/* ---------- one face of a card, rendered from the frozen data ---------- */
function labelled(text) {
  const i = text.indexOf(': ');
  if (i > 0 && text.slice(0, i).split(/\s+/).length <= 6) return `<strong>${esc(text.slice(0, i + 1))}</strong> ${esc(text.slice(i + 2))}`;
  return esc(text);
}
function items(list) {
  let html = '', open = false;
  for (const it of list) {
    if (it[0] === 'body') { if (open) { html += '</ul>'; open = false; } html += `<p>${esc(it[1])}</p>`; continue; }
    if (!open) { html += '<ul>'; open = true; }
    html += it[0] === 'num' ? `<li class="n"><span class="k">${esc(it[1])}</span>${esc(it[2])}</li>` : `<li>${labelled(it[1])}</li>`;
  }
  return html + (open ? '</ul>' : '');
}
function points(list) {
  if (!list || !list.length) return '';
  return `<ul class="pts">${list.map(p => /:\s*$/.test(p) ? `<li class="lead">${esc(p)}</li>` : /^\d+\.\s/.test(p) ? `<li class="numd">${esc(p)}</li>` : `<li>${esc(p)}</li>`).join('')}</ul>`;
}
function diagram(g) {
  const L = t();
  let inner;
  if (g.type === 'dentition') {
    const rows = [[18, 17, 16, 15, 14, 13, 12, 11, 21, 22, 23, 24, 25, 26, 27, 28], [48, 47, 46, 45, 44, 43, 42, 41, 31, 32, 33, 34, 35, 36, 37, 38]];
    const lab = g.row_labels || ['', ''];
    inner = `<div class="teeth">${rows.map((r, k) => `<span class="rl">${esc(lab[k])}</span>${r.map(n => `<span class="${g.highlight.includes(n) ? 'on' : ''}">${n}</span>`).join('')}`).join('')}</div>
      ${g.caption ? `<small>${esc(g.caption)}</small>` : ''}`;
  } else {
    inner = `<div class="panels">${(g.panels || []).map(p => `<div class="panel"><b>${esc(p.label)}</b>${esc(p.caption)}</div>`).join('')}</div>
      ${(g.legend || []).map(x => `<small>${esc(x)}</small>`).join('')}`;
  }
  return `<div class="diag"><p class="lab" style="margin-top:0">${L.diag}</p>${inner}
    <small>${L.diagNote}</small><button type="button" class="link" id="diagbtn">${L.openDiag}</button></div>`;
}
function refs(list) {
  if (!list || !list.length) return '';
  const L = t();
  const groups = ['A', 'B', 'C'].map(k => [k, list.filter(r => r.cls === k)]).filter(g => g[1].length);
  return `<details class="refs"><summary>${L.refs(list.length)}</summary>${groups.map(([k, rs]) => `<h4>${L.cls[k]}</h4><ol>${rs.map(r => `<li>${esc(r.text)}</li>`).join('')}</ol>`).join('')}</details>`;
}
function face(c, side) {
  const L = t(), f = c[side];
  let body = '';
  if (side === 'front') {
    body = `<h2>${esc(f.title)}</h2>
      ${f.question ? `<p class="q">${esc(f.question)}</p>` : ''}
      ${f.text ? `<p>${esc(f.text)}</p>` : ''}
      ${f.audience ? points(f.audience) : ''}
      ${f.recall && f.recall.length ? `<p class="lab">${L.recall}</p><ul class="recall">${f.recall.map(x => `<li>${esc(x)}</li>`).join('')}</ul>` : ''}
      ${f.last_line ? `<p class="lastline">${esc(f.last_line)}</p>` : ''}`;
  } else {
    const src = f.sources_line ? (/^(fonte|fonti|source|sources)\b/i.test(f.sources_line) ? esc(f.sources_line) : `${L.sources}: ${esc(f.sources_line)}`) : '';
    body = `<h2>${esc(f.title)}</h2>
      ${f.intro ? `<p>${esc(f.intro)}</p>` : ''}
      ${points(f.intro_points)}
      ${f.diagram ? diagram(f.diagram) : ''}
      ${(f.boxes || []).map(b => `<section class="box ${b.color === 'coral' ? 'coral' : b.color === 'blue' ? 'blue' : ''}"><h3>${esc(b.heading)}</h3>${items(b.items)}</section>`).join('')}
      ${f.last_line ? `<p class="lastline">${esc(f.last_line)}</p>` : ''}
      ${src ? `<p class="src">${src}</p>` : ''}
      ${refs(f.references)}`;
  }
  return `<article class="card"><div class="card-top"><span class="chip">${esc(c.id)}</span><span class="side">${side === 'front' ? L.front : L.back}</span></div>${body}</article>`;
}

