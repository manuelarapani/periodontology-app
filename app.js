function wireLang() { app.querySelectorAll('[data-lang]').forEach(b => b.onclick = () => setLang(b.dataset.lang)); }

async function setLang(l) {
  if (l === P.lang) return;
  try { await getData(l); } catch (e) { return; }
  P.lang = l; save(P); document.documentElement.lang = l;
  if (S.ses) {
    const d = D(), all = [...d.intro, ...d.cards];
    S.ses.list = S.ses.list.map(c => all.find(x => x.id === c.id));
    if (S.view === 'sum') summary(); else if (S.view === 'legend') legendStep(); else card();
  } else if (S.view === 'login') loginView(); else home();
}

/* ---------- sessions ---------- */
function startModule(m, fromId) {
  const list = D().cards.filter(c => c.module === m);
  startSession('module', list, m, Math.max(0, list.findIndex(c => c.id === fromId)));
}
function startReview(list) {
  const l = list || D().cards.filter(c => rating(c.id) && rating(c.id) <= 2)
    .sort((a, b) => rating(a.id) - rating(b.id) || P.cards[a.id].t - P.cards[b.id].t);
  if (l.length) startSession('review', l, null);
}
function startSession(kind, list, m, i = 0) {
  S.ses = { kind, list, m, i, side: 'front', got: {} };
  card();
}

function head() {
  const L = t(), s = S.ses, d = D();
  const name = s.kind === 'module' ? `${L.module} ${s.m} · ${esc(cap(d.modules[s.m - 1].title))}` : s.kind === 'intro' ? L.intro : L.reviewTitle;
  S.name = name;
  const tot = s.list.length + (s.kind === 'intro' ? 1 : 0), pos = S.view === 'legend' ? tot : s.i + 1;
  const done = S.view === 'legend' ? 1 : (s.i + (s.side === 'back' ? .5 : 0)) / tot;
  return bar(`<button type="button" class="back" id="home">${L.home}</button><span class="where"></span><span class="count">${pos}/${tot}</span>`)
    + `<div class="progress"><i style="width:${(100 * done).toFixed(1)}%"></i></div>`;
}

